-- PequeMundo Digital: tabla de resultados de juego
-- Ejecutar en Supabase > SQL Editor.
create table if not exists public.pmd_results (
  id bigint generated by default as identity primary key,
  student_first_name text not null,
  student_last_name text not null,
  age text not null check (age in ('3 años','4 años','5 años')),
  game text not null check (game in ('keyboard','mouse','miniexcel')),
  level integer not null check (level between 1 and 30),
  score_percent integer not null check (score_percent between 0 and 100),
  passed boolean not null default false,
  metrics jsonb not null default '{}'::jsonb,
  teacher text not null default 'JHILVER ELOY QUISPE BARRAZA',
  created_at timestamptz not null default now()
);

alter table public.pmd_results enable row level security;

-- Permite a estudiantes enviar resultados desde el juego sin iniciar sesión.
drop policy if exists "Students can submit game results" on public.pmd_results;
create policy "Students can submit game results"
on public.pmd_results for insert to anon, authenticated
with check (
  char_length(trim(student_first_name)) > 0
  and char_length(trim(student_last_name)) > 0
  and teacher = 'JHILVER ELOY QUISPE BARRAZA'
);

-- Solo usuarios autenticados (docente) pueden leer los registros.
drop policy if exists "Authenticated teacher can read results" on public.pmd_results;
create policy "Authenticated teacher can read results"
on public.pmd_results for select to authenticated
using (true);

grant insert on public.pmd_results to anon, authenticated;
grant select on public.pmd_results to authenticated;
grant usage, select on sequence public.pmd_results_id_seq to anon, authenticated;
